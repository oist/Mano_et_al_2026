import argparse
from datetime import datetime
import h5py
import numpy as np
from roifile import roiread
import os
import pandas as pd
from skimage import draw
from nptdms import TdmsFile
from concurrent.futures import ProcessPoolExecutor
import functools

def process_contour(cont, j, Y, cell_occupied, neuropil_radius, neuropil_r, baseline_window, baseline_percentile):
    from skimage import draw
    import numpy as np
    import pandas as pd

    rr, cc = draw.polygon(cont[:, 1], cont[:, 0], (Y.shape[1], Y.shape[2]))
    mask = np.zeros_like(Y[0], dtype=np.bool)
    mask[rr, cc] = True
    d = np.zeros_like(Y[0], dtype=np.bool)
    r1, c1 = draw.disk([cont[:, 1].mean(), cont[:, 0].mean()], neuropil_radius, shape=d.shape)
    d[r1, c1] = True
    donut_mask = d ^ mask
    donut_mask[cell_occupied] = False
    rr2, cc2 = np.where(donut_mask)

    obj = Y[:, rr, cc]
    donut = Y[:, rr2, cc2]

    F_cell = obj.mean(axis=1)
    F_neuropil = donut.mean(axis=1)
    F = F_cell - neuropil_r * F_neuropil
    F[F <= 0] = np.nan

    # compute the baseline
    s = pd.Series(F)
    baseline = s.rolling(window=baseline_window, center=True).quantile(baseline_percentile).to_numpy()
    dff = (F - baseline) / baseline

    return {
        "id": j,
        "F_cell": F_cell,
        "F_neuropil": F_neuropil,
        "F": F,
        "baseline": baseline,
        "dff": dff,
    }

def main(img_path, roi_path, tdms_path, save_dir, bad_frames_npy=None,
         neuropil_radius=30, neuropil_r=0.5, baseline_window=200, baseline_percentile=0.2,
         crop_last_two_frames=True, dataset_name="mov",
         pad_before=0, pad_after=0, input_sampling_freq=5000, output_sampling_freq=1000,
         max_workers=None):

    print(f"{datetime.now()} - Loading calcium movie: {img_path}")
    with h5py.File(img_path, "r") as hf:
        Y = hf[dataset_name][:]
    print(f"{datetime.now()} - Done.")

    print(f"{datetime.now()} - Loading ROI objects: {roi_path}")
    rois = roiread(roi_path)
    rois = sorted(rois, key=lambda x: x.name)  # sort the list
    contours = [r.subpixel_coordinates for r in rois]
    print(f"{datetime.now()} - Done.")

    print(f"{datetime.now()} - Loading TDMS file: {tdms_path}")
    f = TdmsFile.read(tdms_path)
    g = f.groups()
    twop = g[0].channels()[0][:]  # line0; TTL generated by 2P scope
    cam = g[0].channels()[1][:]  # line1; TTL from basler camera
    vis = g[0].channels()[2][:]  # line2; TTL from Psychopy
    # rising edge of twop
    twop_re = np.flatnonzero((twop[:-1] < 0.5) & (twop[1:] > 0.5))
    if crop_last_two_frames:
        twop_re = twop_re[:-2]  # crop the last two frames; this is needed for Thorlabs 2P scope
    print(f"{datetime.now()} - Done.")

    print(f"{datetime.now()} - Computing DF/F...")
    cell_occupied = np.zeros_like(Y[0], dtype=np.bool)
    for cont in contours:
        rr, cc = draw.polygon(cont[:, 1], cont[:, 0], (Y.shape[1], Y.shape[2]))
        cell_occupied[rr, cc] = 1

    # Parallelize the loop
    process_func = functools.partial(
        process_contour,
        Y=Y,
        cell_occupied=cell_occupied,
        neuropil_radius=neuropil_radius,
        neuropil_r=neuropil_r,
        baseline_window=baseline_window,
        baseline_percentile=baseline_percentile,
    )

    with ProcessPoolExecutor(max_workers=max_workers) as executor:
        results = list(executor.map(process_func, contours, range(len(contours))))

    print(f"{datetime.now()} - Done.")

    # The rest of the processing and saving logic remains unchanged...
    for x in ["F_cell", "F_neuropil", "F", "baseline", "dff"]:
        y = np.array([r[x] for r in results])

        # pad zeros before or after the 1st axis (along time) if necessary
        y = np.pad(y, [(0, 0), (pad_before, pad_after)], mode="constant", constant_values=0)

        if bad_frames_npy is not None:
            bad_frames = np.load(bad_frames_npy)
            y[:, bad_frames] = np.nan

        # upsample
        YY = np.zeros((y.shape[0], twop.size))
        for i in range(y.shape[0]):
            YY[i, :] = np.interp(np.arange(twop.size), twop_re, y[i, :])

        # downsample
        ratio = int(input_sampling_freq / output_sampling_freq)
        if ratio > 1:
            YY = YY[:, ::ratio]

        # save
        if not os.path.exists(save_dir):
            os.makedirs(save_dir)
        savename = os.path.join(save_dir, "DFF.hdf5")
        with h5py.File(savename, "a", driver="stdio") as hf:
            _ = hf.create_dataset(x, data=YY)

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--img_path", type=str, required=True, help="path to the motion corrected movie (HDF5)")
    parser.add_argument("--roi_path", type=str, required=True, help="path to the ImageJ ROI (.zip)")
    parser.add_argument("--tdms_path", type=str, required=True, help="path to the TDMS file with TTL pulse trains")
    parser.add_argument("--bad_frames", type=str, default=None, help="numpy 1d array")
    parser.add_argument("--save_dir", type=str, required=True, help="directory where all outputs will be saved")
    parser.add_argument("--neuropil_radius", type=int, default=30)
    parser.add_argument("--neuropil_r", type=float, default=0.5)
    parser.add_argument("--baseline_window", type=int, default=200)
    parser.add_argument("--baseline_percentile", type=float, default=0.2)
    parser.add_argument('--crop_last_two_frames', dest='crop_last_two_frames', action='store_true')
    parser.add_argument('--no-crop_last_two_frames', dest='crop_last_two_frames', action='store_false')
    parser.set_defaults(crop_last_two_frames=True)  # Default value
    parser.add_argument("--input_sampling_freq", type=float, default=5000)
    parser.add_argument("--output_sampling_freq", type=float, default=1000)
    parser.add_argument("--dataset_name", type=str, default="mov")
    parser.add_argument("--pad_before", type=int, default=0)
    parser.add_argument("--pad_after", type=int, default=0)
    parser.add_argument("--max_workers", type=int, default=None, help="Number of parallel workers (default: number of CPUs)")
    args = parser.parse_args()

    print(args.crop_last_two_frames)

    main(
        img_path=args.img_path,
        roi_path=args.roi_path,
        tdms_path=args.tdms_path,
        save_dir=args.save_dir,
        bad_frames_npy=args.bad_frames,
        neuropil_radius=args.neuropil_radius,
        neuropil_r=args.neuropil_r,
        baseline_window=args.baseline_window,
        baseline_percentile=args.baseline_percentile,
        crop_last_two_frames=args.crop_last_two_frames,
        dataset_name=args.dataset_name,
        pad_before=args.pad_before,
        pad_after=args.pad_after,
        max_workers=args.max_workers,
    )
